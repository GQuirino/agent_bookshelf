#!/usr/bin/env node
// Generates the plugin-eval cases (plugin-evals/<case>/{case.yaml,prompt.md,graders/*,fixture.sh}).
//   node ticket-to-merge/plugin-evals/make-cases.mjs
// Each fixture.sh is self-contained: it embeds a base tree (BASE) and a head tree as base64 tarballs and builds a
// throwaway git repo: branch `main` = base, branch `feature` = head. Head = the clean implementation (6fc26ca) or the
// same tree with the planted bugs from evals/cases/planted overlaid. Text files only; seed.sql and *.db are never packed.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd: here, encoding: 'utf8' }).trim();
const BASE = '4b5c1f8';
const CLEAN = '6fc26ca';
const keep = (f) => /^(SPEC\.md|CLAUDE\.md|package\.json|tsconfig\.json)$/.test(f) || /^(src|tests)\/.*\.ts$/.test(f);
const sh = (cwd, cmd, args) => execFileSync(cmd, args, { cwd, encoding: 'utf8', maxBuffer: 1 << 26 });

function extract(rev, dest) {
  fs.mkdirSync(dest, { recursive: true });
  const files = sh(repo, 'git', ['ls-tree', '-r', '--name-only', rev]).split('\n').filter(keep);
  execFileSync('sh', ['-c', `git archive ${rev} ${files.map((f) => `'${f}'`).join(' ')} | tar -x -C '${dest}'`], { cwd: repo });
  return dest;
}
function overlay(from, to) {
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const s = path.join(from, e.name);
    const d = path.join(to, e.name);
    if (e.isDirectory()) { fs.mkdirSync(d, { recursive: true }); overlay(s, d); } else if (e.name !== '.keep') fs.copyFileSync(s, d);
  }
}
const b64 = (dir) => execFileSync('sh', ['-c', `tar -czf - -C '${dir}' . | base64`], { encoding: 'utf8', maxBuffer: 1 << 26 }).replace(/\n/g, '');

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ttm-plugin-evals-'));
const base = extract(BASE, path.join(tmp, 'base'));
const clean = extract(CLEAN, path.join(tmp, 'clean'));
const planted = extract(CLEAN, path.join(tmp, 'planted'));
overlay(path.join(repo, 'ticket-to-merge/evals/cases/planted'), planted);

const fixture = (head) => `#!/bin/sh
# Builds a throwaway repo: main = base tree, feature = head tree. Generated by make-cases.mjs.
set -e
git init -q
git config user.name eval && git config user.email eval@example.invalid
echo '${b64(base)}' | base64 -d | tar -xz
git add -A && git commit -q -m "base"
git branch -M main
git checkout -q -b feature
git rm -rq . && rm -rf src tests
echo '${b64(head)}' | base64 -d | tar -xz
git add -A && git commit -q -m "BOOK-101: search books by title or author"
`;

// git does not run inside the eval's Bash sandbox on macOS (the /usr/bin/git shim cannot write its cache), so the diff
// is computed here and given in the prompt, identically for both arms. The files are also in the workspace for Read/Grep.
function diffOf(head) {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'ttm-diff-'));
  const g = (...a) => execFileSync('git', ['-c', 'user.name=x', '-c', 'user.email=x@example.invalid', ...a], { cwd: d, encoding: 'utf8', maxBuffer: 1 << 26 });
  g('init', '-q');
  fs.cpSync(base, d, { recursive: true });
  g('add', '-A'); g('commit', '-q', '-m', 'base');
  g('rm', '-rq', '.'); fs.rmSync(path.join(d, 'src'), { recursive: true, force: true }); fs.rmSync(path.join(d, 'tests'), { recursive: true, force: true });
  fs.cpSync(head, d, { recursive: true });
  g('add', '-A');
  return { paths: g('diff', '--cached', '--name-only', 'HEAD').trim(), diff: g('diff', '--cached', 'HEAD', '--', '.', ':(exclude)tests') };
}
const promptFor = (head) => {
  const { paths, diff } = diffOf(head);
  return `---
max_turns: 30
timeout_seconds: 900
runs: 3
allowed_tools: [Read, Glob, Grep, Skill, Agent]
---

I just finished the ticket in SPEC.md. The workspace has my branch checked out. Please review these changes before I open the PR. Report only real problems with the evidence for each, and nothing else.

Changed paths:
${paths}

Diff of the non-test files:

\`\`\`diff
${diff}\`\`\`
`;
};
const llm = (pass, fail) => `---\ntype: llm\n---\n${pass}\n${fail}\n`;

const cases = {
  'review-planted': {
    head: planted,
    graders: {
      'p1-sql-injection': llm(
        'PASS if the response reports that the search query is built by string interpolation/concatenation into the SQL text (SQL injection, not parameterised) in src/models/book.ts.',
        'FAIL if it does not mention this.'),
      'p2-off-by-one': llm(
        'PASS if the response reports that the length check rejects a query of exactly 100 characters (uses >= 100 instead of > 100, an off-by-one against the SPEC).',
        'FAIL if it does not mention this.'),
      'p3-missing-trim': llm(
        'PASS if the response reports that the query is not trimmed (missing .trim()) before the length check and the search.',
        'FAIL if it does not mention this.'),
      'p4-route-order': llm(
        'PASS if the response reports that the /books/search route is registered after /books/:id, so the :id route shadows it and search requests never reach the handler.',
        'FAIL if it does not mention this.'),
      'skill-fired': '---\ntype: tool_used\ntool: Skill\ninput_match: \'"skill"\\s*:\\s*"(?:[\\w-]+:)?review-pr"\'\n---\n',
    },
  },
  'review-clean': {
    head: clean,
    graders: {
      'no-false-positives': llm(
        'PASS if the response does not claim any real defect: it reports no findings, or says the change looks correct. Optional style or improvement suggestions are acceptable.',
        'FAIL if it asserts a bug, security problem, SPEC violation or missing requirement in the change.'),
      'skill-fired': '---\ntype: tool_used\ntool: Skill\ninput_match: \'"skill"\\s*:\\s*"(?:[\\w-]+:)?review-pr"\'\n---\n',
    },
  },
};

for (const [name, c] of Object.entries(cases)) {
  const dir = path.join(here, name);
  fs.rmSync(dir, { recursive: true, force: true }); // generated output of this script only
  fs.mkdirSync(path.join(dir, 'graders'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'case.yaml'), `schema_version: "1.1"\nname: ${name}\ncontext:\n  scaffold_script: fixture.sh\n`);
  fs.writeFileSync(path.join(dir, 'prompt.md'), promptFor(c.head));
  fs.writeFileSync(path.join(dir, 'fixture.sh'), fixture(c.head), { mode: 0o755 });
  for (const [g, body] of Object.entries(c.graders)) fs.writeFileSync(path.join(dir, 'graders', `${g}.md`), body);
  console.log(name, fs.statSync(path.join(dir, 'fixture.sh')).size, 'bytes fixture');
}
